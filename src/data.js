/* Periodic-table grid position (row 0-based, col 0-based). f-block rows 8 and 9. */
function ptablePos(Z) {
  if (Z === 1) return [0, 0];
  if (Z === 2) return [0, 17];
  const blocks = [[3, 10, 1], [11, 18, 2]];
  for (const [a, b, row] of blocks) if (Z >= a && Z <= b) {
    const i = Z - a; return [row, i < 2 ? i : i + 10];
  }
  if (Z >= 19 && Z <= 36) return [3, Z - 19];
  if (Z >= 37 && Z <= 54) return [4, Z - 37];
  if (Z === 55 || Z === 56) return [5, Z - 55];
  if (Z === 57) return [5, 2];
  if (Z >= 58 && Z <= 71) return [8, Z - 58 + 3];
  if (Z >= 72 && Z <= 86) return [5, Z - 72 + 3];
  if (Z === 87 || Z === 88) return [6, Z - 87];
  if (Z === 89) return [6, 2];
  if (Z >= 90 && Z <= 103) return [9, Z - 90 + 3];
  if (Z >= 104 && Z <= 118) return [6, Z - 104 + 3];
  return [0, 0];
}
function periodOf(Z) {
  if (Z <= 2) return 1; if (Z <= 10) return 2; if (Z <= 18) return 3; if (Z <= 36) return 4;
  if (Z <= 54) return 5; if (Z <= 86) return 6; return Z <= 118 ? 7 : 8;
}

