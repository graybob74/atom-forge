'use strict';
// Writes tools/xtb/afxtb-data.js, Atom Forge xTB's parameters (1.26), from a fit's result (fit.js's output JSON):
// node tools/xtb-fit/mkaf.js <fit.json>, then node tools/xtb/mksrc.js. The second GFN2 refit (refit2.js, XQ.method 4):
// node tools/xtb-fit/mkaf.js <refit.json> --out afxtb2-data.js --id 900002
const fs = require('fs'), path = require('path');
const f = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const flag = (k, d) => { const i = process.argv.indexOf(k); return i < 0 ? d : process.argv[i + 1]; };
const OUT = flag('--out', 'afxtb-data.js'), ID = +flag('--id', 900001), two = OUT !== 'afxtb-data.js';
const r = (v) => +(+v).toPrecision(8);
const el = {}; for (const [z, o] of Object.entries(f.par.el)) { el[z] = {}; for (const [k, v] of Object.entries(o)) el[z][k] = Array.isArray(v) ? v.map(r) : r(v); }
const pair = {}; for (const [k, v] of Object.entries(f.par.pair)) pair[k] = r(v);
const data = { base: f.base, ws: r(f.ws), par: { id: ID, el, pair }, after: f.after || null, ...(two ? { frozen: f.freeze } : {}) };
fs.writeFileSync(path.join(__dirname, '..', 'xtb', OUT), `'use strict';
// ${two ? 'GFN2 (Atom Forge fit), the second GFN2 refit (1.26)' : 'Atom Forge xTB (1.26)'}: its own parameters for H, C, N and O over ${f.base === 1 ? 'GFN1' : 'GFN2'}-xTB's form, with spin
// polarization (spin constants times ws), fitted by tools/xtb-fit/${two ? 'refit2.js' : 'fit.js'} to GMTKN55 (W4-11, BH76, WATER27), g-xTB points
// (hexazine's path, a proton between waters) and measured bond lengths and angles${two ? ', the parameters in frozen kept GFN2\'s' : ''}. Generated by tools/xtb-fit/mkaf.js:
// do not edit. par as gfn${f.base}.js elementP reads it: per element dlev (eV), kcn (x 1 + v), shp (+ v, 0.01 units),
// hub, g3, ra, rz (x 1 + v); per pair the H0 scaling x 1 + v. after: the fit's errors (eV, Å) on fitted and held-out data.
module.exports = ${JSON.stringify(data, null, 1)};
`);
console.log('wrote ' + OUT + ' (base GFN' + f.base + ')');
