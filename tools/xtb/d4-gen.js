'use strict';
// Writes tools/xtb/d4-data.js (the DFT-D4 tables d4.js needs for GFN2-xTB's self-consistent D4) from dftd4's Fortran
// source (LGPL-3.0-or-later): src/dftd4/reference.inc (reference systems: their counts, coordination numbers, GFN2
// charges, hydrogen counts and dynamic polarizabilities at 23 imaginary frequencies; the secondary systems the
// hydrogens are taken off with) and src/dftd4/data/ (covalent radii, electronegativities, chemical hardness, effective
// charges, <r4>/<r2>). Numbers copied as text (only "_wp" removed), elements 1..86.
//
//   git clone --depth 1 https://github.com/dftd4/dftd4.git <dir>/dftd4
//   node tools/xtb/d4-gen.js <dir>
const fs = require('fs'), path = require('path'), { execSync } = require('child_process');

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/xtb/d4-gen.js <dir with dftd4>'); process.exit(1); }
const MAXZ = 86, MREF = 7, NSEC = 17;
const read = p => fs.readFileSync(path.join(dir, 'dftd4', p), 'utf8');
const strip = s => s.split('\n').map(l => l.replace(/!.*$/, '')).join('\n').replace(/&/g, ' ');
const tok = s => (s.match(/[+-]?\d+(?:\.\d*)?(?:[eEdD][+-]?\d+)?(?:_wp)?/g) || []).map(t => t.replace(/_wp$/, '').replace(/^\+/, ''));
const commit = (() => { try { return execSync('git -C ' + JSON.stringify(path.join(dir, 'dftd4')) + ' log -1 --format=%h', { encoding: 'utf8' }).trim(); } catch (e) { return '?'; } })();

// reference.inc: Fortran DATA statements, e.g. "data refq (2, 5) / 0.155_wp /", "data alphaiw(:,2, 5) / ... /"
const inc = strip(read('src/dftd4/reference.inc'));
const want = { refn: [1], refq: [MREF], refh: [MREF], hcount: [MREF], ascale: [MREF], refcovcn: [MREF], refcn: [MREF],
  refsys: [MREF], alphaiw: [23, MREF], sscale: [], secaiw: [23] };
const D = {};
for (const k of Object.keys(want)) D[k] = [];
let count = 0;
for (const m of inc.matchAll(/data\s+(\w+)\s*\(([^)]*)\)\s*\/([^/]*)\//g)) {
  const name = m[1], idx = m[2].split(',').map(s => s.trim()), vals = tok(m[3]);
  if (!want[name]) continue;
  const last = +idx[idx.length - 1];               // the element (or secondary system) is the last index
  const isSec = name === 'sscale' || name === 'secaiw';
  if (!isSec && last > MAXZ) continue;
  if (name === 'alphaiw') { if (vals.length !== 23) throw new Error('alphaiw length'); D.alphaiw[((last - 1) * MREF + (+idx[1] - 1)) * 23] = vals; }
  else if (name === 'secaiw') { if (vals.length !== 23) throw new Error('secaiw length'); D.secaiw[(last - 1) * 23] = vals; }
  else if (name === 'refn' || name === 'sscale') D[name][last - 1] = vals[0];
  else D[name][(last - 1) * MREF + (+idx[0] - 1)] = vals[0];
  count++;
}
// flatten, filling what no DATA statement set with 0 (the Fortran arrays it reads are set for every reference used)
const flat = (name, n, w) => { const a = []; for (let k = 0; k < n; k += w) { const v = D[name][k]; if (w === 1) a.push(v === undefined ? '0' : v); else for (let j = 0; j < w; j++) a.push(v ? v[j] : '0'); } return a; };
const out = {
  refn: flat('refn', MAXZ, 1), refq: flat('refq', MAXZ * MREF, 1), refh: flat('refh', MAXZ * MREF, 1),
  hcount: flat('hcount', MAXZ * MREF, 1), ascale: flat('ascale', MAXZ * MREF, 1), refcovcn: flat('refcovcn', MAXZ * MREF, 1),
  refcn: flat('refcn', MAXZ * MREF, 1), refsys: flat('refsys', MAXZ * MREF, 1),
  alphaiw: flat('alphaiw', MAXZ * MREF * 23, 23), sscale: flat('sscale', NSEC, 1), secaiw: flat('secaiw', NSEC * 23, 23),
};
for (let z = 1; z <= MAXZ; z++) if (!(+out.refn[z - 1] >= 1)) throw new Error('no references for Z = ' + z);

// data/*.f90: per-element constants
const dat = (f, name) => {
  const s = strip(read('src/dftd4/data/' + f)), m = s.match(new RegExp(name + '\\(max_elem\\)\\s*=[^\\[]*\\[([\\s\\S]*?)\\]'));
  if (!m) throw new Error(name + ' not found in ' + f);
  const v = tok(m[1]); if (v.length < MAXZ) throw new Error(name + ' short'); return v.slice(0, MAXZ);
};
out.covrad = dat('covrad.f90', 'covalent_rad_2009');   // Å (the Fortran multiplies by aatoau, and by 4/3 for the CN)
out.en = dat('en.f90', 'pauling_en');
out.eta = dat('hardness.f90', 'chemical_hardness');
out.zeff = dat('zeff.f90', 'effective_nuclear_charge');
out.r4r2 = dat('r4r2.f90', 'r4_over_r2');              // d4.js takes sqrt(0.5 * r4r2 * sqrt(Z)) as the Fortran does

const fmt = (a, per = 12) => { const rows = []; for (let k = 0; k < a.length; k += per) rows.push('    ' + a.slice(k, k + per).join(', ')); return '[ // ' + a.length + '\n' + rows.join(',\n') + ']'; };
let s = `'use strict';
// DFT-D4 tables for elements 1..86 (GFN2-xTB's reference charges). Generated by tools/xtb/d4-gen.js; do not edit.
// Source: dftd4 ${commit} (src/dftd4/reference.inc, src/dftd4/data/*.f90; LGPL-3.0-or-later). Numbers copied as text.
// Per-reference tables are [(Z - 1) * 7 + ref]; alphaiw [((Z - 1) * 7 + ref) * 23 + frequency]; secaiw [(sys - 1) * 23 + k].
module.exports = {
  maxZ: ${MAXZ}, mref: ${MREF},
`;
for (const [k, v] of Object.entries(out)) s += `  ${k}: ${fmt(v)},\n`;
s += '};\n';
fs.writeFileSync(path.join(__dirname, 'd4-data.js'), s);
console.log('wrote tools/xtb/d4-data.js', s.length, 'bytes from', count, 'DATA statements');
