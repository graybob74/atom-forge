function slaterToGauss(ng, n, l, zeta) {
  if (n > 5 && !(n === 6 && ng === 6)) throw new Error('STO-nG: principal quantum number not supported');
  const ityp = l === 0 ? n : l === 1 ? 4 + n : l === 2 ? 7 + n : l === 3 ? 9 + n : 10 + n; // 1-based
  const z2 = zeta * zeta;
  let a, c;
  const tab = (A, C, K) => { a = []; c = []; for (let k = 0; k < K; k++) { a.push(num(A[(ityp - 1) * K + k]) * z2); c.push(C ? num(C[(ityp - 1) * K + k]) : 1); } };
  if (ng === 1) { a = [num(T.pAlpha1[ityp - 1]) * z2]; c = [1]; }
  else if (ng === 2) tab(T.pAlpha2, T.pCoeff2, 2);
  else if (ng === 3) tab(T.pAlpha3, T.pCoeff3, 3);
  else if (ng === 4) tab(T.pAlpha4, T.pCoeff4, 4);
  else if (ng === 5) tab(T.pAlpha5, T.pCoeff5, 5);
  else if (ng === 6) {
    if (n === 6) {
      if (l === 0) { a = T.pAlpha6s.map(x => num(x) * z2); c = T.pCoeff6s.map(num); }
      else if (l === 1) { a = T.pAlpha6p.map(x => num(x) * z2); c = T.pCoeff6p.map(num); }
      else throw new Error('STO-6G: 6d not supported');
    } else if ((n === 4 || n === 5) && l <= 1) {
      // shared-exponent 4sp / 5sp sets (Pietro et al.), as GFN1 uses
      a = []; c = [];
      for (let k = 0; k < 6; k++) {
        a.push(num(T.pAlpha6sp[(n - 4) * 6 + k]) * z2);
        c.push(num((l === 0 ? T.pCoeff6sp_s : T.pCoeff6sp_p)[(n - 4) * 6 + k]));
      }
    } else tab(T.pAlpha6, T.pCoeff6, 6);
  } else throw new Error('STO-nG: ng must be 1..6');
  // normalize the primitives
  for (let k = 0; k < ng; k++) c[k] = c[k] * Math.pow(TOP * a[k], 0.75) * Math.pow(Math.sqrt(4 * a[k]), l) / Math.sqrt(DFACT[l]);
  return { l, alpha: a, coeff: c };
}

// Gram-Schmidt: make cgto j orthogonal to cgto i (both s functions here; basis/ortho.f90)
function orthogonalize(ci, cj) {
  if (ci.l !== cj.l) return;
  let ov = 0;
  for (let p = 0; p < ci.alpha.length; p++) for (let q = 0; q < cj.alpha.length; q++)
    ov += ci.coeff[p] * cj.coeff[q] * Math.pow(Math.sqrt(Math.PI / (ci.alpha[p] + cj.alpha[q])), 3);
  const alpha = cj.alpha.concat(ci.alpha), coeff = cj.coeff.concat(ci.coeff.map(x => -ov * x));
  let nrm = 0;
  for (let p = 0; p < alpha.length; p++) for (let q = 0; q < alpha.length; q++)
    nrm += coeff[p] * coeff[q] * Math.pow(Math.sqrt(Math.PI / (alpha[p] + alpha[q])), 3);
  cj.alpha = alpha; cj.coeff = coeff.map(x => x / Math.sqrt(nrm));
}

