//
// A line-by-line port of the reference implementation tblite (LGPL-3.0-or-later; src/tblite/xtb/gfn1.f90, h0.f90,
// basis/, integral/, coulomb/, repulsion/, scf/, wavefunction/) and of the data it takes from mctc-lib (covalent and
// atomic radii, Pauling electronegativities, the exponential coordination number). Same units as tblite inside:
