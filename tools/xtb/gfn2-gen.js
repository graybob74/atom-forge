'use strict';
// Writes tools/xtb/gfn2-data.js (the GFN2-xTB element tables gfn2.js needs) from tblite's Fortran source
// (src/tblite/xtb/gfn2.f90, LGPL-3.0-or-later). The numbers are copied as text (only the "_wp" suffix removed), so
// nothing is rounded on the way; the scale factors the Fortran applies to a table (evtoau, 0.01, 0.1, 1 +) are applied
// in gfn2.js, where each table is used.
//
//   git clone --depth 1 https://github.com/tblite/tblite.git <dir>/tblite
//   node tools/xtb/gfn2-gen.js <dir>
const fs = require('fs'), path = require('path'), { execSync } = require('child_process');

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/xtb/gfn2-gen.js <dir with tblite>'); process.exit(1); }
const src = fs.readFileSync(path.join(dir, 'tblite/src/tblite/xtb/gfn2.f90'), 'utf8')
  .split('\n').map(l => l.replace(/!.*$/, '')).join('\n');
const commit = (() => { try { return execSync('git -C ' + JSON.stringify(path.join(dir, 'tblite')) + ' log -1 --format=%h', { encoding: 'utf8' }).trim(); } catch (e) { return '?'; } })();
const tok = s => (s.match(/[+-]?\d+(?:\.\d*)?(?:[eEdD][+-]?\d+)?(?:_wp)?/g) || []).map(t => t.replace(/_wp$/, '').replace(/^\+/, ''));
function table(name, n) {
  const m = src.match(new RegExp('::\\s*' + name + '\\s*\\([^)]*\\)\\s*=[^\\[]*\\[([\\s\\S]*?)\\]'));
  if (!m) throw new Error('table ' + name + ' not found');
  const v = tok(m[1]);
  if (n && v.length < n) throw new Error(name + ': ' + v.length + ' numbers, ' + n + ' expected');
  return n ? v.slice(0, n) : v;
}
const T = {
  rep_alpha: table('rep_alpha', 86), rep_zeff: table('rep_zeff', 86),
  hubbard_parameter: table('hubbard_parameter', 86),
  shell_hubbard: table('shell_hubbard', 258),          // 1 + these (Fortran: 1.0_wp + reshape(...))
  p_hubbard_derivs: table('p_hubbard_derivs', 86),     // x 0.1
  nshell: table('nshell', 86), ang_shell: table('ang_shell', 258),
  principal_quantum_number: table('principal_quantum_number', 258),
  number_of_primitives: table('number_of_primitives', 258),
  p_shpoly: table('p_shpoly', 258),                    // x 0.01, indexed by angular momentum (0:2, Z)
  p_kcn: table('p_kcn', 258),                          // x evtoau, indexed by angular momentum
  reference_occ: table('reference_occ', 258),          // indexed by angular momentum
  slater_exponent: table('slater_exponent', 258),      // by shell
  p_selfenergy: table('p_selfenergy', 258),            // x evtoau, by shell
  p_dkernel: table('p_dkernel', 86), p_qkernel: table('p_qkernel', 86), // x 0.01
  p_vcn: table('p_vcn', 86), p_rad: table('p_rad', 86),                 // Bohr
};
const scal = (re) => { const m = src.match(re); if (!m) throw new Error('scalar ' + re); return m[1]; };
const G = {
  s6: scal(/s6\s*=\s*([\d.]+)_wp/), s8: scal(/s8\s*=\s*([\d.]+)_wp/), a1: scal(/a1\s*=\s*([\d.]+)_wp/),
  a2: scal(/a2\s*=\s*([\d.]+)_wp/), s9: scal(/s9\s*=\s*([\d.]+)_wp/),
  rep_kexp: scal(/rep_kexp\s*=\s*([\d.]+)_wp/), rep_kexp_light: scal(/rep_kexp_light\s*=\s*([\d.]+)_wp/),
  rep_rexp: scal(/rep_rexp\s*=\s*([\d.]+)_wp/), wexp: scal(/wexp\s*=\s*([\d.]+)_wp/),
  enscale: scal(/enscale\s*=\s*([\d.e-]+)_wp/), gexp: scal(/gexp\s*=\s*([\d.]+)_wp/),
  mp_dmp3: scal(/mp_dmp3\s*=\s*([\d.]+)_wp/), mp_dmp5: scal(/mp_dmp5\s*=\s*([\d.]+)_wp/),
  mp_shift: scal(/mp_shift\s*=\s*([\d.]+)_wp/), mp_kexp: scal(/mp_kexp\s*=\s*([\d.]+)_wp/),
  mp_rmax: scal(/mp_rmax\s*=\s*([\d.]+)_wp/),
};
const fmt = (a, per = 12) => { const rows = []; for (let k = 0; k < a.length; k += per) rows.push('    ' + a.slice(k, k + per).join(', ')); return '[ // ' + a.length + '\n' + rows.join(',\n') + ']'; };
let out = `'use strict';
// GFN2-xTB element tables for elements 1..86. Generated by tools/xtb/gfn2-gen.js; do not edit by hand.
// Source: tblite ${commit} (src/tblite/xtb/gfn2.f90, LGPL-3.0-or-later). Numbers copied as text; the Fortran's scale
// factors are applied in gfn2.js. Tables by shell or by angular momentum are (3, Z) column-major: [(Z - 1) * 3 + k].
module.exports = {
  G: ${JSON.stringify(G)},
`;
for (const [k, v] of Object.entries(T)) out += `  ${k}: ${fmt(v)},\n`;
out += '};\n';
fs.writeFileSync(path.join(__dirname, 'gfn2-data.js'), out);
console.log('wrote tools/xtb/gfn2-data.js', out.length, 'bytes; constants', JSON.stringify(G));
