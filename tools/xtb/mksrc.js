// Writes src/xtb.js, the page's copy of the GFN1-xTB and D3(BJ) code (tools/xtb/gfn1.js, d3.js, d3-data.js) and, since
// 1.26, of GFN2-xTB and its D4 (gfn2.js, gfn2-data.js, d4.js, d4-data.js) and of spin polarization for both (spin.js,
// spin-data.js); those stay the source and are what check.js,
// check-d3.js and check-gfn2.js test: each file in its own scope, under one global, XTB.
// Run after changing any of them: node tools/xtb/mksrc.js
const fs = require('fs'), path = require('path');
const rd = (f) => fs.readFileSync(path.join(__dirname, f), 'utf8').replace(/^'use strict';\s*/m, '');
const mod = (f) => `  M[${JSON.stringify('./' + f)}] = (() => { const module = { exports: {} };\n${rd(f)}\n  return module.exports; })();\n`;
const out = `/* ------------------------------------------------------------------ GFN1-xTB and D3(BJ) (Experimental: quantum bonds, 1.22), GFN2-xTB and D4 (1.26)
   Generated by tools/xtb/mksrc.js from tools/xtb/gfn1.js, d3.js, d3-data.js, gfn2.js, gfn2-data.js, d4.js and d4-data.js:
   do not edit here. XTB.gfn1Energy(Z, xyz Å, charge, uhf, opts), XTB.d3Disp(Z, xyz Å, opts) and XTB.gfn2Energy(Z, xyz Å,
   charge, uhf, opts) (its D4 dispersion included): energies in eV, gradients in eV/Å (tools/xtb/check.js, check-d3.js,
   check-gfn2.js and check-spin.js compare them with tblite and simple-dftd3); opts.spin: spin-polarized (1.26). Ported
   from tblite, simple-dftd3, dftd4 and mctc-lib (LGPL-3.0-or-later). */
const XTB = (() => {
  const M = {}, require = (n) => M[n];
${mod('d3-data.js')}${mod('d3.js')}${mod('spin-data.js')}${mod('spin.js')}${mod('gfn1.js')}${mod('gfn2-data.js')}${mod('d4-data.js')}${mod('d4.js')}${mod('gfn2.js')}  return { gfn1Energy: M['./gfn1.js'].gfn1Energy, nAO: M['./gfn1.js'].nAO, d3Disp: M['./d3.js'].d3Disp, AUTOEV: M['./gfn1.js'].AUTOEV, BOHR: M['./gfn1.js'].BOHR,
    gfn2Energy: M['./gfn2.js'].gfn2Energy, nAO2: M['./gfn2.js'].nAO };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', '..', 'src', 'xtb.js'), out);
console.log('wrote src/xtb.js', out.length, 'bytes');
