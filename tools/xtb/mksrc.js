// Writes src/xtb.js, the page's copy of the GFN1-xTB and D3(BJ) code (tools/xtb/gfn1.js, d3.js, d3-data.js, which stay the
// source and are what check.js and check-d3.js test): each file in its own scope, under one global, XTB.
// Run after changing any of them: node tools/xtb/mksrc.js
const fs = require('fs'), path = require('path');
const rd = (f) => fs.readFileSync(path.join(__dirname, f), 'utf8').replace(/^'use strict';\s*/m, '');
const mod = (f) => `  M[${JSON.stringify('./' + f)}] = (() => { const module = { exports: {} };\n${rd(f)}\n  return module.exports; })();\n`;
const out = `/* ------------------------------------------------------------------ GFN1-xTB and D3(BJ) (Experimental: quantum bonds, 1.22)
   Generated by tools/xtb/mksrc.js from tools/xtb/gfn1.js, d3.js and d3-data.js: do not edit here. XTB.gfn1Energy(Z, xyz Å,
   charge, uhf, opts) and XTB.d3Disp(Z, xyz Å, opts): energies in eV, gradients in eV/Å (tools/xtb/check.js, check-d3.js
   compare them with tblite and simple-dftd3). */
const XTB = (() => {
  const M = {}, require = (n) => M[n];
${mod('d3-data.js')}${mod('d3.js')}${mod('gfn1.js')}  return { gfn1Energy: M['./gfn1.js'].gfn1Energy, d3Disp: M['./d3.js'].d3Disp, AUTOEV: M['./gfn1.js'].AUTOEV, BOHR: M['./gfn1.js'].BOHR };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', '..', 'src', 'xtb.js'), out);
console.log('wrote src/xtb.js', out.length, 'bytes');
