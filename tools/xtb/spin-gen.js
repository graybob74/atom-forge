'use strict';
// Writes tools/xtb/spin-data.js (the spin constants W_ll' of spin-polarized GFN-xTB, 1.26) from tblite's Fortran source
// (src/tblite/data/spin.f90, LGPL-3.0-or-later; Neugebauer, Bädorf, Ehlert, Hansen and Grimme, J. Comput. Chem. 44,
// 2120 (2023)). The numbers are copied as text (only the "_wp" suffix removed): six per element (ss, sp, pp, sd, pd, dd,
// Hartree), H to Rn.
//
//   git clone --depth 1 https://github.com/tblite/tblite.git <dir>/tblite
//   node tools/xtb/spin-gen.js <dir>
const fs = require('fs'), path = require('path'), { execSync } = require('child_process');
const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/xtb/spin-gen.js <dir with tblite>'); process.exit(1); }
const src = fs.readFileSync(path.join(dir, 'tblite/src/tblite/data/spin.f90'), 'utf8').split('\n').map(l => l.replace(/!.*$/, '')).join('\n');
const commit = (() => { try { return execSync('git -C ' + JSON.stringify(path.join(dir, 'tblite')) + ' log -1 --format=%h', { encoding: 'utf8' }).trim(); } catch (e) { return '?'; } })();
const m = src.match(/spin_constants\(6,\s*86\)\s*=\s*reshape\(\[([\s\S]*?)\]/);
if (!m) throw new Error('spin_constants not found');
const v = (m[1].match(/[+-]?\d+\.\d*(?:_wp)/g) || []).map(t => t.replace(/_wp$/, ''));
if (v.length !== 6 * 86) throw new Error(v.length + ' numbers, 516 expected');
const rows = [];
for (let z = 0; z < 86; z++) rows.push('  ' + v.slice(6 * z, 6 * z + 6).map(s => JSON.stringify(s)).join(', ') + ',');
fs.writeFileSync(path.join(__dirname, 'spin-data.js'), `'use strict';
// Spin constants of spin-polarized GFN-xTB (Hartree; per element ss, sp, pp, sd, pd, dd), H to Rn. Generated by
// tools/xtb/spin-gen.js from tblite ${commit} src/tblite/data/spin.f90 (LGPL-3.0-or-later): do not edit.
module.exports = { W: [
${rows.join('\n')}
] };
`);
console.log('wrote spin-data.js from tblite', commit);
